package seng202.team5.models;

import seng202.team5.data.RouteDAO;
import seng202.team5.models.locations.Bar;
import seng202.team5.models.locations.DistanceMatrix;
import seng202.team5.models.types.FeatureType;
import seng202.team5.models.types.Theme;

import java.time.Duration;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * Contains an ordered group of locations which create a bar crawl Route. This is what is created by the bar choosing
 * algorithm and what is then displayed by the Map in JavaFX
 * @author Theo Baker
 */

public class Route {

    private int routeID;
    private String name;
    private String description;
    private final List<Bar> bars;
    private final int totalDistanceMetres;
    private final LocalDate createdDate;
    private final String ownerUsername;
    /**
     * Speed estimated end users to walk at. Determined as slower than average walking speed from <a href="https://en.wikipedia.org/wiki/Preferred_walking_speed">Wikipedia</a> article<br>
     * <br>
     * 1.11 m/s, 15 min/km, 4 km/h
     */
    private final static double WALKING_SPEED = 1.1;
    private final int estimatedTime;
    /**
     * Constructor for loading Route from
     * @param routeID Generated by mariaDB when saved
     * @param name Name chosen by user when saved
     * @param description Description written by user when saved
     * @param bars List of Bars in the route in order
     * @param createdDate date the route was created
     */
    public Route(int routeID, String name, String description, List<Bar> bars, LocalDate createdDate, String username) {
        if (name == null || name.isEmpty()) {
            throw new IllegalArgumentException("Name cannot be null or empty");
        }
        if (bars == null || bars.size() < 2) {
            throw new IllegalArgumentException("Bars cannot be null or empty");
        }
        this.routeID = routeID;
        this.name = name;
        this.description = description == null ? "" : description;
        this.bars = bars;
        this.totalDistanceMetres = calculateTotalDistanceMetres(bars);
        this.createdDate = createdDate;
        this.estimatedTime = (int) (totalDistanceMetres / WALKING_SPEED);
        this.ownerUsername = username;
    }

    /**
     Used when generating Route with n
     @param bars
     */
    public Route(List<Bar> bars) {
        this(-1, "GENERATED ROUTE", "", bars, LocalDate.now(), "Anonymous");}

    public void setRouteID(int id) {
        this.routeID = id;
    }

    private int calculateTotalDistanceMetres(List<Bar> barsInOrder) {
        DistanceMatrix distanceMatrix = new DistanceMatrix("/json/data/distance-matrix.json");
        int distance = 0;
        for (int i = 0; i < barsInOrder.size()-1; i++) {
            distance += distanceMatrix.getDistanceMetres(barsInOrder.get(i), barsInOrder.get(i+1));
        }
        return distance;
    }

    public int getNumStops() {
        return bars.size();
    }

    public double getTotalDistanceKm() {
        return (double) getTotalDistanceMetres() / 1000;
    }

    public int getTotalDistanceMetres() {
        return totalDistanceMetres;
    }

    /**
     * Finds all featuretypes included in Bars in Route
     * @return List of FeatureTypes included in this Route
     */
    public List<FeatureType> getFeatureTypes() {
        Set<FeatureType> features = new HashSet<>();
        for (Bar bar : bars) {
            features.addAll(bar.getFeatureTypes());
        }
        return new ArrayList<>(features);
    }

    /**
     * Finds all Themes of Bar in the Route
     * @return List of Themes included in the Route
     */
    public List<Theme> getThemes() {
        Set<Theme> themes = new HashSet<>();
        for (Bar bar : bars) {
            themes.add(bar.getTheme());
        }
        return new ArrayList<>(themes);
    }

    public List<Bar> getBars() {
        return bars;
    }

    @Override
    public String toString() {
        String title = "ROUTE: " + this.name + "; " + getTotalDistanceKm() + "km" + "\n" + this.description + "\n";
        String bars = "BARS: \n" + this.bars.stream().map(Bar::toString).collect(Collectors.joining()) + "\n";
        String themes = "THEMES: " + this.getThemes().stream().map(Theme::toString).collect(Collectors.joining(", ")) + "\n";
        String features = "FEATURES: " + this.getFeatureTypes().stream().map(FeatureType::toString).collect(Collectors.joining(", ")) + "\n";
        return title + bars + themes + features;
    }

    public Bar getStartBar() {
        return bars.getFirst();
    }

    public Bar getEndBar() {
        return bars.getLast();
    }

    public int getRouteID() {
        return routeID;
    }

    public String getName() {
        return name;
    }

    public String getDescription() {
        return description;
    }

    public LocalDate getCreatedDate() {
        return createdDate;
    }

    public int getEstimatedTime() {
        return estimatedTime;
    }

    public String getFormattedTime() {
        long totalMins = estimatedTime / 60;
        long hours = totalMins / 60;
        long mins = totalMins % 60;

        List<String> parts = new ArrayList<>();
        if (hours != 0) {
            parts.add(formatUnit(hours, "hr"));
        }
        if (mins != 0) {
            parts.add(formatUnit(mins, "min"));
        }
        return String.join(" ", parts);
    }

    private static String formatUnit(long value, String unit) {
        return value + " " + unit + (value == 1 ? "" : "s");
    }

    public void setName(String name) {
        this.name = name;
    }

    public void setDesc(String description) {
        this.description = description;
    }

    public String getOwnerUsername() {
        return this.ownerUsername;
    }
}
